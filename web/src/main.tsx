import { StrictMode, Suspense } from "react";
import { DataBoundary, DataReady } from "./components/DataBoundary";
import PageLoader from "./components/PageLoader";
import { createRoot } from "react-dom/client";
import { BrowserRouter } from "react-router-dom";
import "./styles/global.css";
import "./styles/app.css";
import { SyncProvider } from "./lib/sync-provider";
import { ThemeProvider } from "./lib/theme";
import { I18nProvider } from "./lib/i18n";
import { ReminderProvider } from "./lib/reminder";
import { AiProvider } from "./lib/ai";
import App from "./App";

// Follows are per-conference, so FollowProvider is mounted inside the conference
// layout (ConferenceLayout). Theme, login and D1 sync are site-wide.
createRoot(document.getElementById("root")!).render(
  <StrictMode>
    <BrowserRouter>
      <ThemeProvider>
        <I18nProvider>
          <DataBoundary><Suspense fallback={<PageLoader />}><DataReady>
          <SyncProvider>
            {/* Preference providers notify the shared sync provider. */}
            <ReminderProvider>
              <AiProvider>
                <App />
              </AiProvider>
            </ReminderProvider>
          </SyncProvider>
          </DataReady></Suspense></DataBoundary>
        </I18nProvider>
      </ThemeProvider>
    </BrowserRouter>
  </StrictMode>,
);

// Register the service worker (generated by scripts/build-sw.mjs) in production
// only, so the app is installable and works offline after the first visit. It
// auto-updates (skipWaiting + clientsClaim) on the next load. Dev has no SW.
if (import.meta.env.PROD && "serviceWorker" in navigator) {
  window.addEventListener("load", () => {
    navigator.serviceWorker.register("/sw.js").catch(() => {});
  });
}
